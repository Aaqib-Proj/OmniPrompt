// Writes dist/.htaccess after a build.
//
// Two things have to be in that file and nowhere else:
//   1. The SPA rewrite. Without it Apache 404s every deep link (/explore,
//      /prompts/:slug) because no such file exists on disk.
//   2. A Content-Security-Policy whose script hashes match the inline <script>
//      in index.html. Hard-coding the hash would silently rot the moment that
//      script changed, so it is derived from the built HTML on every build.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const distHtml = resolve(root, 'dist/index.html');

if (!existsSync(distHtml)) {
  console.error('postbuild-htaccess: dist/index.html not found — run the build first.');
  process.exit(1);
}

const html = readFileSync(distHtml, 'utf8');

// CSP hashes cover the exact bytes between the tags, so grab them verbatim.
const inlineScripts = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
const scriptHashes = inlineScripts.map(
  (body) => `'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`
);

/** The API origin the bundle was built against, so connect-src doesn't block it. */
function apiOrigin() {
  const envFile = resolve(root, '.env.production');
  const fallback = 'https://api.syncnomy.com';
  if (!existsSync(envFile)) return fallback;
  const match = readFileSync(envFile, 'utf8').match(/^VITE_API_URL\s*=\s*"?([^"\r\n]+)"?/m);
  if (!match) return fallback;
  try {
    return new URL(match[1]).origin;
  } catch {
    return fallback;
  }
}

const csp = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'self'",
  "form-action 'self'",
  `script-src 'self' ${scriptHashes.join(' ')} https://accounts.google.com`.replace(/\s+/g, ' '),
  // React sets element styles directly, which CSP counts as inline style.
  // Google's sign-in widget pulls its own stylesheet from accounts.google.com.
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com https://accounts.google.com",
  "font-src 'self' data: https://fonts.gstatic.com",
  // Prompt outputs are hosted on whatever CDN the creator used.
  "img-src 'self' data: blob: https:",
  "media-src 'self' blob: https:",
  `connect-src 'self' ${apiOrigin()} https://accounts.google.com`,
  'frame-src https://accounts.google.com',
  "worker-src 'self' blob:",
  'upgrade-insecure-requests',
].join('; ');

const htaccess = `# Generated by scripts/postbuild-htaccess.mjs — do not edit by hand.
# Rebuild (npm run build) to regenerate.

Options -Indexes
DirectoryIndex index.html

<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${csp}"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "geolocation=(), microphone=(), camera=(), payment=()"
  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"

  # Hashed filenames can be cached forever; the entry HTML never can, or users
  # keep booting an old bundle that points at deleted asset files.
  <FilesMatch "\\.(js|css|woff2?|png|jpg|jpeg|gif|svg|webp|mp4|webm|ico)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(html|webmanifest)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

# Dotfiles and env files must never be served, whatever ends up in this folder.
<FilesMatch "^\\.|(\\.env|\\.map|\\.log|package(-lock)?\\.json|tsconfig.*\\.json)$">
  Require all denied
</FilesMatch>

# Single-page app: serve real files, send everything else to index.html so the
# router can handle the URL.
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /
  RewriteRule ^index\\.html$ - [L]
  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]
  RewriteRule . /index.html [L]
</IfModule>
`;

writeFileSync(resolve(root, 'dist/.htaccess'), htaccess, 'utf8');
console.log(
  `postbuild-htaccess: wrote dist/.htaccess (CSP covers ${scriptHashes.length} inline script${
    scriptHashes.length === 1 ? '' : 's'
  }, api origin ${apiOrigin()})`
);
